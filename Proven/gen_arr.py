#!/usr/bin/env python3
"""Writes Proven/ArrWords.lean: step lemmas for the words `Proven/ArrCode.lean` adds to the compiler:
`add t_k, x0, a_i` (i = 4..7, k = 0..6), `add a_v, x0, t0` (v = 4..7), `lbu t0, 0(t0)`, `sb t1, 0(t0)`,
and family lemmas `step_var8`, `step_mv8` dispatching on the indices (i, v = 0..3: the existing lemmas).
usage: python3 Proven/gen_arr.py > Proven/ArrWords.lean"""
T = [5, 6, 7, 28, 29, 30, 31]
encR = lambda f7, f3, rd, rs1, rs2: f7 << 25 | rs2 << 20 | rs1 << 15 | f3 << 12 | rd << 7 | 0x33
HYP = "{s : St} (h : Cfg s) {pc : BitVec 64} (hpc : s.regs.get? .PC = some pc) (hok : pcOK pc)"
out = [f"""/- GENERATED by `python3 Proven/gen_arr.py > Proven/ArrWords.lean`; do not edit.
Step lemmas against the Sail RV64 model for the words `Proven/ArrCode.lean` adds. -/
import Proven.ArrCode
import Proven.Words
import Proven.Loop
import Proven.MemStep
open LeanRV64D LeanRV64D.Functions Sail Sail.ConcurrencyInterfaceV1

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false

namespace Proven

namespace W8
"""]
for i in range(4, 8):
    for k in range(7):
        out.append(f"theorem var_{i}_{k} {HYP} (hi : instrAt s pc (iVar8 {i} {k})) :\n"
                   f"    ∃ s', Next s s' (pc + 4) (T {k}) (getX s {10 + i}) s.mem := by\n"
                   f"  rw [show iVar8 {i} {k} = 0x{encR(0, 0, T[k], 0, 10 + i):08x}#32 by decide] at hi; simp only [T]; step_word")
for v in range(4, 8):
    out.append(f"theorem mv_{v} {HYP} (hi : instrAt s pc (iMv8 {v})) :\n"
               f"    ∃ s', Next s s' (pc + 4) {10 + v} (getX s 5) s.mem := by\n"
               f"  rw [show iMv8 {v} = 0x{encR(0, 0, 10 + v, 0, 5):08x}#32 by decide] at hi; step_word")
out.append(f"""theorem lbuT {HYP} (hi : instrAt s pc 0x0002c283#32)
    (ha : 0x80000000 ≤ (getX s 5).toNat ∧ (getX s 5).toNat + 1 ≤ 0x100000000) {{b : BitVec 8}}
    (hb : s.mem[(getX s 5).toNat]? = some b) :
    ∃ s', Next s s' (pc + 4) 5 (b.setWidth 64) s.mem := by mem_word
theorem sbT {HYP} (hi : instrAt s pc 0x00628023#32)
    (ha : 0x80000000 ≤ (getX s 5).toNat ∧ (getX s 5).toNat + 1 ≤ 0x100000000) :
    ∃ s', Next s s' (pc + 4) 0 0 (s.mem.insert (getX s 5).toNat ((getX s 6).setWidth 8)) := by mem_word
end W8

variable {HYP}
include h hpc hok
""")
def split(v, lo, hi):
    return f"obtain {' | '.join(['rfl'] * (hi - lo))} : {' ∨ '.join(f'{v} = {i}' for i in range(lo, hi))} := by omega"
out.append("theorem step_var8 (i : Fin 8) (k : Nat) (hk : k < 7) (hi : instrAt s pc (iVar8 i k)) :\n"
           "    ∃ s', Next s s' (pc + 4) (T k) (getX s (A8 i)) s.mem := by\n"
           "  obtain ⟨i, hi8⟩ := i\n"
           f"  {split('i', 0, 8)}")
for i in range(4):
    out.append(f"  · exact step_var h hpc hok {i} k (by omega) (by decide) hi")
for i in range(4, 8):
    out.append(f"  · {split('k', 0, 7)}")
    for k in range(7):
        out.append(f"    · exact W8.var_{i}_{k} h hpc hok hi")
out.append("")
out.append("theorem step_mv8 (v : Fin 8) (hi : instrAt s pc (iMv8 v)) :\n"
           "    ∃ s', Next s s' (pc + 4) (A8 v) (getX s 5) s.mem := by\n"
           "  obtain ⟨v, hv⟩ := v\n"
           f"  {split('v', 0, 8)}")
for v in range(4):
    out.append(f"  · exact step_mv{v} h hpc hok hi")
for v in range(4, 8):
    out.append(f"  · exact W8.mv_{v} h hpc hok hi")
out.append("\nend Proven")
print("\n".join(out))
