#!/usr/bin/env python3
"""Writes Proven/Words.lean: one `step_word` lemma per concrete word the compiler of Proven/Code.lean emits,
and family lemmas dispatching on the indices. Keep T, N and the encodings in sync with Code.lean.
usage: python3 Proven/gen_words.py > Proven/Words.lean"""
T = [5, 6, 7, 28, 29, 30, 31, 14, 15, 16, 17]; N = len(T)
encR = lambda f7, f3, rd, rs1, rs2: f7 << 25 | rs2 << 20 | rs1 << 15 | f3 << 12 | rd << 7 | 0x33
encI = lambda f3, imm, rd, rs1: imm << 20 | rs1 << 15 | f3 << 12 | rd << 7 | 0x13
OPS = {"add": (0, 0), "sub": (0x20, 0), "and": (0, 7), "or": (0, 6), "xor": (0, 4), "shl": (0, 1),
       "lshr": (0, 5), "ashr": (0x20, 5), "ult": (0, 3), "slt": (0, 2)}
X, Y, Z = "(getX s (T {k}))", "(getX s (T ({k} + 1)))", "(getX s (T ({k} + 2)))"
# family: (word expression, encoding, value, number of k, extra arguments)
fams = {
    "op": [(f"iOp .{o} {{k}}", lambda k, o=o: encR(*OPS[o], T[k], T[k], T[k + 1]), f"(Op.eval .{o} {X} {Y})", o)
           for o in OPS],
    "var": [(f"iVar {i} {{k}}", lambda k, i=i: encR(0, 0, T[k], 0, 10 + i), f"(getX s (A {i}))", str(i)) for i in range(4)],
    "zero": [("iZero {k}", lambda k: encI(0, 0, T[k], 0), "0", None)],
    "shl": [("iShl {k}", lambda k: encI(1, 1, T[k], T[k]), f"({X} <<< 1)", None)],
    "inc": [("iInc {k}", lambda k: encI(0, 1, T[k], T[k]), f"({X} + 1)", None)],
    "seqz": [("iSeqz {k}", lambda k: encI(3, 1, T[k], T[k]), f"(if {X} = 0 then 1 else 0)", None)],
    "snez": [("iSnez {k}", lambda k: encR(0, 3, T[k], 0, T[k]), f"(if {X} = 0 then 0 else 1)", None)],
    "neg": [("iNeg {k}", lambda k: encR(0x20, 0, T[k], 0, T[k]), f"(-{X})", None)],
    "xor2": [("iXor2 {k}", lambda k: encR(0, 4, T[k], T[k], T[k + 2]), f"({X} ^^^ {Z})", None)],
}
KS = {"op": N - 1, "var": N, "zero": N, "shl": N, "inc": N, "seqz": N - 1, "snez": N - 2, "neg": N - 2, "xor2": N - 2}
HYP = "{s : St} (h : Cfg s) {pc : BitVec 64} (hpc : s.regs.get? .PC = some pc) (hok : pcOK pc)"
out = [f"""/- GENERATED by `python3 Proven/gen_words.py > Proven/Words.lean`; do not edit.
Step lemmas against the Sail RV64 model for every word `Proven/Code.lean` emits. -/
import Proven.Code
import Proven.Step
open LeanRV64D LeanRV64D.Functions Sail Sail.ConcurrencyInterfaceV1

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false

namespace Proven

/-! ## Normal forms for the new instructions' results -/

@[simp] theorem log2_xlen_eq : Functions.log2_xlen = 6 := rfl
@[simp] theorem srl_eq {{n m}} (x : BitVec n) (y : BitVec m) : shift_bits_right x y = x >>> y.toNat := rfl
@[simp] theorem sra_eq {{m}} (x : BitVec 64) (y : BitVec m) : shift_bits_right_arith x y = x.sshiftRight y.toNat := by
  simp [shift_bits_right_arith]
@[simp] theorem bool_to_bit_ext (b : Bool) : zero_extend (m := 64) (bool_to_bit b) = if b then 1#64 else 0#64 := by
  cases b <;> rfl
@[simp] theorem ite_ult (a b : BitVec 64) :
    (if a.toNat < b.toNat then 1#64 else 0#64) = if a < b then 1#64 else 0#64 := by
  simp [BitVec.lt_def]
@[simp] theorem ite_slt (a b : BitVec 64) :
    (if a.toInt < b.toInt then 1#64 else 0#64) = if a.slt b then 1#64 else 0#64 := by
  simp [BitVec.slt_iff_toInt_lt]
@[simp] theorem ite_seqz (a : BitVec 64) :
    (if (a.toNat : Int) < 1 then 1#64 else 0#64) = if a = 0#64 then 1#64 else 0#64 := by
  have : (a.toNat : Int) < 1 ↔ a = 0#64 := by rw [← BitVec.toNat_inj]; simp; omega
  simp [this]
@[simp] theorem ite_snez (a : BitVec 64) :
    (if 0 < a.toNat then 1#64 else 0#64) = if a = 0#64 then 0#64 else 1#64 := by
  have : 0 < a.toNat ↔ ¬a = 0#64 := by rw [← BitVec.toNat_inj]; simp; omega
  by_cases ha : a = 0#64 <;> simp [ha, this]

namespace W
"""]
for f, insts in fams.items():
    for (w, enc, v, tag) in insts:
        for k in range(KS[f]):
            name = f"{f}_{tag}_{k}" if tag else f"{f}_{k}"
            out.append(f"theorem {name} {HYP} (hi : instrAt s pc ({w.format(k=k)})) :\n"
                       f"    ∃ s', Next s s' (pc + 4) (T {k}) {v.format(k=k)} s.mem := by\n"
                       f"  rw [show {w.format(k=k)} = 0x{enc(k):08x}#32 by decide] at hi; simp only [T, A, Op.eval]; step_word")
out.append(f"""end W

variable {HYP}
include h hpc hok
""")
def split(v, n):
    return f"obtain {' | '.join(['rfl'] * n)} : {' ∨ '.join(f'{v} = {i}' for i in range(n))} := by omega"
def fam(f, sig, val, n, arms):
    out.append(f"theorem step_{f} {sig} :\n    ∃ s', Next s s' (pc + 4) (T k) {val} s.mem := by\n  {split('k', n)}")
    for k in range(n):
        if len(arms(k)) == 1: out.append(f"  · {arms(k)[0][1]}"); continue
        out.append(f"  · {arms(k)[0][0]}")
        out.extend(f"    · {a}" for _, a in arms(k))
    out.append("")
ex = "h hpc hok hi"
fam("op", f"(op : Op) (k : Nat) (hk : k < {N-1}) (hi : instrAt s pc (iOp op k))", "(op.raw (getX s (T k)) (getX s (T (k + 1))))",
    N - 1, lambda k: [("cases op", f"exact W.op_{'xor' if o == 'eq' else o}_{k} {ex}") for o in list(OPS) + ["eq"]])
fam("var", f"(i k : Nat) (hk : k < {N}) (hi4 : i < 4) (hi : instrAt s pc (iVar i k))", "(getX s (A i))",
    N, lambda k: [(split('i', 4), f"exact W.var_{i}_{k} {ex}") for i in range(4)])
for f, n in [("zero", N), ("shl", N), ("inc", N), ("seqz", N - 1), ("snez", N - 2), ("neg", N - 2), ("xor2", N - 2)]:
    (w, _, v, _), = fams[f]
    fam(f, f"(k : Nat) (hk : k < {n}) (hi : instrAt s pc ({w.format(k='k')}))", v.format(k="k"), n,
        lambda k, f=f: [(None, f"exact W.{f}_{k} {ex}")])
out.append(f"""theorem step_res (hi : instrAt s pc iRes) : ∃ s', Next s s' (pc + 4) 10 (getX s 5) s.mem := by
  rw [show iRes = 0x00500533#32 by decide] at hi; step_word

theorem step_ret (hi : instrAt s pc iRet) (he : (getX s 1).toNat % 2 = 0) :
    ∃ s', Next s s' (getX s 1) 0 0 s.mem := by
  rw [show iRet = 0x00008067#32 by decide] at hi; step_word

end Proven""")
print("\n".join(out))
