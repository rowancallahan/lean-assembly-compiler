#!/usr/bin/env python3
"""Writes Riscv/Steps/BranchWords.lean: step lemmas, against the Sail RV64 model, for conditional branches
`b<op> rs1, rs2, off` with a SYMBOLIC offset, for every op and every register pair below, and `jal rd, off`.
usage: python3 Riscv/Steps/gen_branch.py > Riscv/Steps/BranchWords.lean"""
R1 = [5, 6, 10, 11, 12, 13]   # t0 t1 a0 a1 a2 a3
R2 = [0, 5, 6]                # x0 t0 t1
RD = [0]                      # jal x0 (plain jump)
X = lambda r: "0#64" if r == 0 else f"getX s {r}"
N = lambda r: "0" if r == 0 else f"(getX s {r})"   # where `.toInt` / `.toNat` is taken
# f3: name, taken condition, not-taken condition (in the forms the model's decisions simplify to)
OPS = {
    0: ("beq", "{a} = {b}", "¬{a} = {b}"),
    1: ("bne", "¬{a} = {b}", "{a} = {b}"),
    4: ("blt", "{ia} < {ib}", "¬{ia} < {ib}"),
    5: ("bge", "¬{ia} < {ib}", "{ia} < {ib}"),
    6: ("bltu", "{na} < {nb}", "¬{na} < {nb}"),
    7: ("bgeu", "¬{na} < {nb}", "{na} < {nb}"),
}
HYP = "{s : St} (h : Cfg s) {pc : BitVec 64} (hpc : s.regs.get? .PC = some pc) (hok : pcOK pc)"
out = [f"""/- GENERATED by `python3 Riscv/Steps/gen_branch.py > Riscv/Steps/BranchWords.lean`; do not edit.
Branch / jump step lemmas (symbolic offset) against the Sail RV64 model; machinery in `Riscv/Steps/Branch.lean`. -/
import Riscv.Steps.Branch
open LeanRV64D LeanRV64D.Functions Sail Sail.ConcurrencyInterfaceV1

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option linter.unusedVariables false

namespace Proven

theorem bcond_iff_toInt (a b : BitVec 64) : a.slt b = true ↔ a.toInt < b.toInt := by simp [BitVec.slt_iff_toInt_lt]
theorem bcond_iff_toNat (a b : BitVec 64) : a.ult b = true ↔ a.toNat < b.toNat := by simp [BitVec.ult_iff_lt, BitVec.lt_def]
theorem bcond_iff_toInt' (a b : BitVec 64) : a.slt b = false ↔ ¬a.toInt < b.toInt := by
  rw [← bcond_iff_toInt]; simp
theorem bcond_iff_toNat' (a b : BitVec 64) : a.ult b = false ↔ ¬a.toNat < b.toNat := by
  rw [← bcond_iff_toNat]; simp

variable {HYP}
include h hpc hok
"""]
for f3, (name, tk, nt) in OPS.items():
    for r1 in R1:
        for r2 in R2:
            if r1 == r2 or (r2 == 0 and f3 in (6, 7)): continue  # bltu/bgeu with x0: constant
            a, b = X(r1), X(r2)
            ia, ib = (f"{N(r)}.toInt" if r else "0" for r in (r1, r2))
            na, nb = (f"{N(r)}.toNat" if r else "0" for r in (r1, r2))
            F = dict(a=a, b=b, ia=ia, ib=ib, na=na, nb=nb)
            w = f"wB {f3} {r1} {r2} o"
            n = f"{name}_{r1}_{r2}"
            out.append(f"""theorem {n}_t (o : BitVec 12) (hi : instrAt s pc ({w})) (hc : {tk.format(**F)}) :
    ∃ s', Next s s' (pc + boff o) 0 0 s.mem := by bstep
theorem {n}_n (o : BitVec 12) (hi : instrAt s pc ({w})) (hc : {nt.format(**F)}) :
    ∃ s', Next s s' (pc + 4) 0 0 s.mem := by bstep
theorem step_{n} (o : BitVec 12) (hi : instrAt s pc ({w})) :
    ∃ s', Next s s' (if bcond {f3} (getX s {r1}) (getX s {r2}) then pc + boff o else pc + 4) 0 0 s.mem := by
  {"have e0 : getX s 0 = 0#64 := rfl; simp only [e0]" if r2 == 0 else "skip"}
  by_cases hc : {tk.format(**F)}
  · have key : bcond {f3} ({a}) ({b}) = true ↔ {tk.format(**F)} := by
      simp [bcond, bcond_iff_toInt, bcond_iff_toNat, bcond_iff_toInt', bcond_iff_toNat']
    rw [if_pos (key.2 hc)]; exact {n}_t h hpc hok o hi hc
  · have key : bcond {f3} ({a}) ({b}) = true ↔ {tk.format(**F)} := by
      simp [bcond, bcond_iff_toInt, bcond_iff_toNat, bcond_iff_toInt', bcond_iff_toNat']
    rw [if_neg (fun e => hc (key.1 e))]
    exact {n}_n h hpc hok o hi (by simpa using hc)
""")
for rd in RD:
    out.append(f"""theorem step_jal_{rd} (o : BitVec 20) (hi : instrAt s pc (wJ {rd} o)) :
    ∃ s', Next s s' (pc + joff o) {rd} (pc + 4) s.mem := by bstep
""")
out.append("end Proven")
print("\n".join(out))
