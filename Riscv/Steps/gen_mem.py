#!/usr/bin/env python3
"""Writes Riscv/Steps/MemWords.lean: one `mem_word` lemma per concrete load/store word
(`lbu/ld rd, 0(rs1)`, `sb/sd rs2, 0(rs1)`, data register in D, address register in B),
and family lemmas dispatching on the register numbers.
usage: python3 Riscv/Steps/gen_mem.py > Riscv/Steps/MemWords.lean"""
import sys
D = [5, 6, 7, 28, 29, 30, 31, 14, 15, 16, 17]  # t0..t6, a4..a7 (the compiler's temporaries)
B = [9, 10, 11, 12, 13]                        # s1, a0..a3
if len(sys.argv) > 1: D, B = D[:2], B[:2]  # quick test
enc = {"lbu": lambda d, a: a << 15 | 4 << 12 | d << 7 | 0x03, "ld": lambda d, a: a << 15 | 3 << 12 | d << 7 | 0x03,
       "sb": lambda d, a: d << 20 | a << 15 | 0 << 12 | 0x23, "sd": lambda d, a: d << 20 | a << 15 | 3 << 12 | 0x23}
HYP = "{s : St} (h : Cfg s) {pc : BitVec 64} (hpc : s.regs.get? .PC = some pc) (hok : pcOK pc)"
X = lambda a: f"(getX s {a}).toNat"
def ram(a, n): return f"(ha : 0x80000000 ≤ {X(a)} ∧ {X(a)} + {n} ≤ 0x100000000)"
BYTES = " ".join(f"b{i}" for i in range(8))
def body(op, d, a):
    if op == "lbu":
        return (f"{ram(a, 1)} {{b : BitVec 8}} (hb : s.mem[{X(a)}]? = some b)",
                f"(pc + 4) {d} (b.setWidth 64) s.mem")
    if op == "sb":
        return (ram(a, 1), f"(pc + 4) 0 0 (s.mem.insert {X(a)} ((getX s {d}).setWidth 8))")
    al = f"(hal : {X(a)} % 8 = 0)"
    if op == "ld":
        hb = " ".join(f"(h{i} : s.mem[{X(a)}{' + ' + str(i) if i else ''}]? = some b{i})" for i in range(8))
        return (f"{ram(a, 8)} {al}\n    {{{BYTES} : BitVec 8}} {hb}",
                f"(pc + 4) {d} (b7 ++ b6 ++ b5 ++ b4 ++ b3 ++ b2 ++ b1 ++ b0) s.mem")
    return (f"{ram(a, 8)} {al}", f"(pc + 4) 0 0 (storeBytes s.mem {X(a)} (le8 (getX s {d})))")

out = [f"""/- GENERATED by `python3 Riscv/Steps/gen_mem.py > Riscv/Steps/MemWords.lean`; do not edit.
Step lemmas against the Sail RV64 model for `lbu/ld rd, 0(rs1)` and `sb/sd rs2, 0(rs1)`,
rd/rs2 ∈ {D}, rs1 ∈ {B}. -/
import Riscv.Steps.MemStep
open LeanRV64D LeanRV64D.Functions Sail Sail.ConcurrencyInterfaceV1

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
set_option linter.unusedVariables false

namespace Proven

/-- data registers (the compiler's temporaries) and address registers (`s1, a0..a3`) -/
def memD : List (Fin 32) := {D}
def memB : List (Fin 32) := {B}

def iLbu (rd rs1 : Fin 32) : BitVec 32 := BitVec.ofNat 32 (rs1.val <<< 15 ||| 4 <<< 12 ||| rd.val <<< 7 ||| 0x03)
def iLd (rd rs1 : Fin 32) : BitVec 32 := BitVec.ofNat 32 (rs1.val <<< 15 ||| 3 <<< 12 ||| rd.val <<< 7 ||| 0x03)
def iSb (rs2 rs1 : Fin 32) : BitVec 32 := BitVec.ofNat 32 (rs2.val <<< 20 ||| rs1.val <<< 15 ||| 0 <<< 12 ||| 0x23)
def iSd (rs2 rs1 : Fin 32) : BitVec 32 := BitVec.ofNat 32 (rs2.val <<< 20 ||| rs1.val <<< 15 ||| 3 <<< 12 ||| 0x23)

namespace MW
"""]
for op in enc:
    for d in D:
        for a in B:
            hyps, concl = body(op, d, a)
            out.append(f"theorem {op}_{d}_{a} {HYP} (hi : instrAt s pc 0x{enc[op](d, a):08x}#32)\n    {hyps} :\n"
                       f"    ∃ s', Next s s' {concl} := by mem_word")
out.append("end MW\n")

def fam(op, args, hyps, concl, call):
    I = {"lbu": "iLbu", "ld": "iLd", "sb": "iSb", "sd": "iSd"}[op]
    out.append(f"theorem step_{op}_raw {HYP} ({args} : Fin 32) (hd : {args.split()[0]} ∈ memD) (hb : rs1 ∈ memB)\n"
               f"    (hi : instrAt s pc ({I} {args}))\n    {hyps} :\n    ∃ s', Next s s' {concl} := by")
    d = args.split()[0]
    out.append(f"  simp only [memD, memB, List.mem_cons, List.not_mem_nil, or_false] at hd hb")
    out.append(f"  rcases hd with {' | '.join(['rfl'] * len(D))} <;> rcases hb with {' | '.join(['rfl'] * len(B))}")
    for dd in D:
        for a in B:
            out.append(f"  · rw [show {I} {dd} {a} = 0x{enc[op](dd, a):08x}#32 by decide] at hi; exact MW.{op}_{dd}_{a} {call}")
    out.append("")
sub = lambda t: t.replace("(getX s {d})", "(getX s rd)")
fam("lbu", "rd rs1", f"{ram('rs1', 1)} {{b : BitVec 8}} (hb1 : s.mem[{X('rs1')}]? = some b)",
    "(pc + 4) rd (b.setWidth 64) s.mem", "h hpc hok hi ha hb1")
fam("sb", "rs2 rs1", ram('rs1', 1), f"(pc + 4) 0 0 (s.mem.insert {X('rs1')} ((getX s rs2).setWidth 8))", "h hpc hok hi ha")
hb = " ".join(f"(h{i} : s.mem[{X('rs1')}{' + ' + str(i) if i else ''}]? = some b{i})" for i in range(8))
fam("ld", "rd rs1", f"{ram('rs1', 8)} (hal : {X('rs1')} % 8 = 0)\n    {{{BYTES} : BitVec 8}} {hb}",
    "(pc + 4) rd (b7 ++ b6 ++ b5 ++ b4 ++ b3 ++ b2 ++ b1 ++ b0) s.mem", "h hpc hok hi ha hal h0 h1 h2 h3 h4 h5 h6 h7")
fam("sd", "rs2 rs1", f"{ram('rs1', 8)} (hal : {X('rs1')} % 8 = 0)",
    f"(pc + 4) 0 0 (storeBytes s.mem {X('rs1')} (le8 (getX s rs2)))", "h hpc hok hi ha hal")
out.append("end Proven")
print("\n".join(out))
