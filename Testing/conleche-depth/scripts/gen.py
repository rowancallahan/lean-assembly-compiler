import re,sys,os
R='/tmp/claude-0/cl/con-leche/'
def path(m): return R+m.replace('.','/')+'.lean'
seen=[];ext=set()
def visit(m):
    if m in seen: return
    for l in open(path(m)):
        mm=re.match(r'^(?:public )?import (all )?(\S+)',l)
        if mm:
            x=mm.group(2)
            if x.startswith('ConLeche.'): visit(x)
            else: ext.add(x)
    seen.append(m)
for m in sys.argv[2:]: visit(m)
out=['import Riscv.Frontx.Machine','import Riscv.Frontx.IndCmd']+['import '+x for x in sorted(ext) if x not in('Init.Util','Init')]
out.append('-- generated by Testing/conleche-depth/gen.py: con-leche @6810492c1, files concatenated in import order; only edits: E1 (module/public/expose headers dropped)')
for m in seen:
    src=open(path(m)).read().split('\n'); out.append(f'-- ===== {m} ({len(src)} lines) =====\nsection')
    for l in src:
        if re.match(r'^(module|public import|import|meta import|public meta import|import all)\b',l) or l.strip() in('@[expose] public section','public section'): out.append('-- E1: '+l); continue
        out.append(l)
    out.append('end')
open(sys.argv[1],'w').write('\n'.join(out))
print(seen)
