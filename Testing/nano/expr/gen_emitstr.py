#!/usr/bin/env python3
"""Writes Nano/Expr/EmitStr.lean: E's phrase table `ew i j` = word j of phrase i (8 bytes, little endian; a phrase
ends at its first word whose top byte is 0, or at a 0 word). Ids are fixed: Nano/Expr/Emit.lean uses them."""
P = [" @", " c", " \\", " >", " h", "\n", "D",
     " c UInt64", " c Buf", " @ c List.{0} c UInt8", " c Nat", " @ @ c Prod.{0,0}",
     " @ @ @ c OfNat.ofNat.{0}", " @ c UInt64.instOfNat", " @ c instOfNatNat"]
OPS = [("HAdd.hAdd", "instHAdd", "instAddUInt64"), ("HSub.hSub", "instHSub", "instSubUInt64"),
       ("HMul.hMul", "instHMul", "instMulUInt64"), ("HAnd.hAnd", "instHAndOfAndOp", "instAndOpUInt64"),
       ("HOr.hOr", "instHOrOfOrOp", "instOrOpUInt64"),
       ("HShiftLeft.hShiftLeft", "instHShiftLeftOfShiftLeft", "instShiftLeftUInt64"),
       ("HShiftRight.hShiftRight", "instHShiftRightOfShiftRight", "instShiftRightUInt64")]
P += [f" @ @ @ @ @ @ c {f}.{{0,0,0}} c UInt64 c UInt64 c UInt64 @ @ c {i}.{{0}} c UInt64 c {j}" for f, i, j in OPS]
BEQ = " @ @ @ @ c BEq.beq.{0} c UInt64 @ @ c instBEqOfDecidableEq.{0} c UInt64 c instDecidableEqUInt64"
P += [" @ @ @ @ @ c ite.{1}", " @ @ @ c Eq.{1} c Bool" + BEQ, " c Bool.true @ @ c instDecidableEqBool" + BEQ,
      " c Bool.true", " @ @ @ @ c LT.lt.{0} c UInt64 c instLTUInt64", " @ @ c UInt64.decLt",
      " @ @ @ @ @ c Prod.casesOn.{1,0,0}", " @ @ @ @ c Prod.mk.{0,0}", " @ c List.nil.{0} c UInt8", " c bnew"]
P += [f" c {n}" for n in ["len'", "rd", "len", "put", "bnew", "bsize", "bget", "bset", "bpush"]]
P += [" @ @ @ @ c Nat.casesOn.{1} \\ c Nat", " \\ c Nat", " #", " n", " ", "R\n", " !"]
BEQN = BEQ.replace("UInt64", "Nat")
P += [" @ @ @ c Eq.{1} c Bool" + BEQN, " c Bool.true @ @ c instDecidableEqBool" + BEQN,
      " @ @ @ @ c LT.lt.{0} c Nat c instLTNat", " @ @ c Nat.decLt"]
# phrases E writes as ` !<id>` (S-compact; expand.py restores S): the long fixed ones
ABBREV = [i for i in range(len(P)) if 11 < i < 32 or i in (9, 11, 41) or 47 < i]
assert len(P) == 52 and P[22] == " @ @ @ @ @ c ite.{1}" and P[41].startswith(" @ @ @ @ c Nat.casesOn") and P[32] == " c len'"
def words(s):
    b = s.encode(); w = [int.from_bytes(b[i:i+8], 'little') for i in range(0, len(b), 8)]
    if len(b) % 8 == 0: w.append(0)
    return w
rows = []
for i, s in enumerate(P):
    w = words(s); assert len(w) <= 32
    inner = " else ".join(f"if j == {k} then {v}" for k, v in enumerate(w)) + " else 0"
    rows.append(f"  if i == {i} then ({inner})")
body = "\n  else ".join(r.strip() for r in rows) + "\n  else 0"
out = ("/- GENERATED by Testing/nano/expr/gen_emitstr.py.  Do not edit.  E's phrase table: word j of phrase i. -/\n"
       "import Nano.Main.Prelude\nnamespace C\n\ndef ew (i j : UInt64) : UInt64 :=\n  " + body + "\n\nend C\n")
open("Nano/Expr/EmitStr.lean", "w").write(out)
