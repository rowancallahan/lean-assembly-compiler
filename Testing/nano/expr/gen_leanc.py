#!/usr/bin/env python3
"""gen_leanc.py LEAN_S.x OUT.lean : writes Lean's normalized Expr of every def of C as `ExprSpec.X` data
(`ExprLeanC.defs`: (name, type, value) per def, in def order), from the `X` lines lean_side.sh (XOUT=true) prints
while reading Lean's environment. TRUSTED step: lean_expr.lean's reading of the environment (N1-N4, EXPR.md §3) and
this verbatim copy into Lean syntax."""
import sys
rows = [l.rstrip('\n').split('\t') for l in open(sys.argv[1])]
assert all(len(r) == 3 and r[0].startswith('X ') for r in rows)
out = ["/- GENERATED by Testing/nano/expr/gen_leanc.py (Lean's environment, via lean_expr.lean).  Do not edit.",
       "Lean's elaborated Expr of each def of C, normalized (EXPR.md §3), as `ExprSpec.X` data. -/",
       "import Nano.Expr.ExprSpec", "set_option maxRecDepth 100000", "namespace ExprLeanC", "open ExprSpec", ""]
for i, (n, t, v) in enumerate(rows):
    out.append(f"def t{i} : X := {t}")
    out.append(f"def v{i} : X := {v}")
names = [r[0][2:] for r in rows]
out.append("")
out.append("def defs : List (String × X × X) := [")
out.append(",\n".join(f'  ("{n}", t{i}, v{i})' for i, n in enumerate(names)))
out += ["]", "", "end ExprLeanC", ""]
open(sys.argv[2], 'w').write("\n".join(out))
