#!/usr/bin/env python3
"""(5) writes Nano/Agree.lean: for every corpus program the same text as a Lean string (input of nanoElab) and as real
Lean `def`s (Lean's elaborator is the reference), with kernel-checked theorems
  elabEq : nanoElab bytes = some P          (decide +kernel, P printed by show.lean)
  agree : ∀ args, (nanoElab src).bind (·.eval args) = some (f args)   (rfl after rewriting with elab)"""
import os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nanolib import *
D = os.path.dirname(os.path.abspath(__file__)); W = os.path.join(D, "work"); ROOT = os.path.abspath(os.path.join(D, "..", ".."))
os.makedirs(W, exist_ok=True)
for i, s in enumerate(CORPUS): open(f"{W}/c{i}.nano", "w").write(s)
out = subprocess.run(f"cd {ROOT} && PATH=$HOME/.elan/bin:$PATH lake env lean --run Testing/nano/show.lean " + " ".join(f"{W}/c{i}.nano" for i in range(len(CORPUS))),
                     shell=True, check=True, capture_output=True, text=True).stdout.splitlines()
assert len(out) == len(CORPUS) and "NONE" not in out
lit = lambda s: '"' + s.replace("\\", "\\\\").replace("\n", "\\n") + '"'
L = ["import Nano.Gen", "/- GENERATED by Testing/nano/gen_agree.py: elaborator agreement with Lean's real elaborator. -/", "namespace Nano.Agree", "open Nano", "set_option linter.unusedVariables false", ""]
for i, (s, P) in enumerate(zip(CORPUS, out)):
    k = entry_arity(s); name = re.findall(r"^def\s+(\w+)", s, re.M)[-1]
    xs = " ".join(f"x{j}" for j in range(k))
    L += [f"namespace P{i}", s, f"def src : String := {lit(s)}",
          f"theorem bytes_eq : src.toUTF8.toList = src.toList.map (fun c => c.toNat.toUInt8) := by decide +kernel",
          f"theorem elabEq : nanoElab (src.toList.map (fun c => c.toNat.toUInt8)) = some {P} := by decide +kernel",
          f"theorem agree : ∀ {xs} : UInt64, (nanoElab src.toUTF8.toList).bind (·.eval [{', '.join(f'x{j}' for j in range(k))}]) = some ({name} {xs}) := by",
          f"  intro {xs}; rw [bytes_eq, elabEq]; rfl" if k else "  rw [bytes_eq, elabEq]; rfl",
          f"end P{i}", ""]
L += ["end Nano.Agree", ""]
open(os.path.join(ROOT, "Nano", "Agree.lean"), "w").write("\n".join(L))
print(len(CORPUS), "programs")
