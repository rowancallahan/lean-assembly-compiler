#!/usr/bin/env python3
"""writes Nano/AgreeInt.lean: for every Int64 corpus program (nanolib.INT_CORPUS) the same text as a Lean string (input
of nanoElabT) and as real Lean `def`s (Lean's elaborator is the reference), with kernel-checked theorems
  elabEq : nanoElabT bytes = some (true, P)   (decide +kernel; `true` = the program's type is Int64)
  agree : ∀ args : Int64, (nanoElabT src).bind (Int64 meaning) = some (f args)   (rfl after rewriting with elabEq)
  run   : ∀ args, nanoRun P (encIs args) = some (encI (f args))  (the byte-level meaning, 8-byte LE two's complement)"""
import os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nanolib import *
D = os.path.dirname(os.path.abspath(__file__)); W = os.path.join(D, "work"); ROOT = os.path.abspath(os.path.join(D, "..", ".."))
os.makedirs(W, exist_ok=True)
for i, s in enumerate(INT_CORPUS): open(f"{W}/i{i}.nano", "w").write(s)
out = subprocess.run(f"cd {ROOT} && PATH=$HOME/.elan/bin:$PATH lake env lean --run Testing/nano/show.lean " + " ".join(f"{W}/i{i}.nano" for i in range(len(INT_CORPUS))),
                     shell=True, check=True, capture_output=True, text=True).stdout.splitlines()
assert len(out) == len(INT_CORPUS) and "NONE" not in out, out
lit = lambda s: '"' + s.replace("\\", "\\\\").replace("\n", "\\n") + '"'
L = ["import Nano.Int", "import Nano.Elab",
     "/- GENERATED by Testing/nano/gen_agree_int.py: Int64 elaborator agreement with Lean's real elaborator. -/",
     "namespace Nano.AgreeInt", "open Nano", "set_option linter.unusedVariables false", "",
     "/-- the Int64 meaning of an elaborated source (none unless its type is Int64) -/",
     "def evalT (r : Bool × Prog) (args : List Int64) : Option Int64 := if r.1 then r.2.evalI args else none", ""]
for i, (s, P) in enumerate(zip(INT_CORPUS, out)):
    k = entry_arity(s); name = re.findall(r"^def\s+(\w+)", s, re.M)[-1]
    xs = " ".join(f"x{j}" for j in range(k)); lst = "[" + ", ".join(f"x{j}" for j in range(k)) + "]"
    L += [f"namespace P{i}", s, f"def src : String := {lit(s)}",
          f"theorem bytes_eq : src.toUTF8.toList = src.toList.map (fun c => c.toNat.toUInt8) := by decide +kernel",
          f"theorem elabEq : nanoElabT (src.toList.map (fun c => c.toNat.toUInt8)) = some (true, {P}) := by decide +kernel",
          f"theorem agree : ∀ {xs} : Int64, (nanoElabT src.toUTF8.toList).bind (evalT · {lst}) = some ({name} {xs}) := by" if k else
          f"theorem agree : (nanoElabT src.toUTF8.toList).bind (evalT · []) = some {name} := by",
          f"  intro {xs}; rw [bytes_eq, elabEq]; rfl" if k else "  rw [bytes_eq, elabEq]; rfl",
          f"theorem run : ∀ {xs} : Int64, nanoRun {P} (encIs {lst}) = some (encI ({name} {xs})) := by" if k else
          f"theorem run : nanoRun {P} (encIs []) = some (encI {name}) := by",
          (f"  intro {xs}; rw [nanoRun_int _ _ rfl]; " if k else "  rw [nanoRun_int _ _ rfl]; ") + "simp only [Prog.evalI, List.length_cons, List.length_nil, if_true]; rfl",
          f"end P{i}", ""]
L += ["end Nano.AgreeInt", ""]
open(os.path.join(ROOT, "Nano", "AgreeInt.lean"), "w").write("\n".join(L))
print(len(INT_CORPUS), "programs")
