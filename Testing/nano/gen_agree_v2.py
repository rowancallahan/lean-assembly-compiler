"""Generate Nano/V2Agree.lean: for each corpus source (UInt64 and Int64) the v2 elaborator's result (`elabEq`, by
`decide +kernel`) and its meaning = Lean's own elaboration of the SAME text, for all inputs (`agree`).
usage: python3 Testing/nano/gen_agree_v2.py"""
import json, os, re, subprocess
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
# not here (the generic tactic below does not close them; both agree in Testing/nano/fuzz2.py):
#  "def s (x : Int64) : Int64 := if x < 0 then -1 else if x == 0 then 0 else 1\ndef f (x y : Int64) : Int64 := s x * 3 + s y"
#  "def f (x : UInt64) : UInt64 := if x < 18446744073709551616 then 1 else 2"
SRCS = [
 "def f (x y : UInt64) : UInt64 := if x < y then x else y",
 "def f (x y : Int64) : Int64 := if x < y then x else y",
 "def f (x y : UInt64) : UInt64 := if x <= y then y - x else x - y",
 "def f (x y : Int64) : Int64 := if x <= y then y - x else x - y",
 "def f (x y : UInt64) : UInt64 := if x == y then 1 else 2",
 "def f (x y : Int64) : Int64 := if x == y then 1 else 2",
 "def f (x : Int64) : Int64 := if x < 0 then 0 - x else x",
 "def f (x : UInt64) : UInt64 := if x == 0 then 1 else if x == 1 then 1 else x * 2",
 "def m (a b : UInt64) : UInt64 := if a < b then b else a\ndef f (x y z : UInt64) : UInt64 := m (m x y) z",
 "def f (x y : UInt64) : UInt64 := let d := x - y; if d < 9223372036854775808 then d else 0 - d",
 "def c (x l h : Int64) : Int64 := if x < l then l else if h < x then h else x\ndef f (x : Int64) : Int64 := c x (-100) 100",
 "def d (c : UInt64) : UInt64 := if 48 <= c then (if c <= 57 then 1 else 0) else 0\ndef f (x : UInt64) : UInt64 := d x + d (x + 1) * 2",
 "def f (x y : UInt64) : UInt64 := if x + 1 < y * 2 then x - y else y - x",
 "def f (x y : UInt64) : UInt64 := (if x < y then 1 else 2) + 3",
 "def f (x y : UInt64) : UInt64 := if x < y then let z := x; z * z else 0",
 "def f (x y : UInt64) : UInt64 := let z := if x < y then x else y; z + 1",
 "def f (x y : Int64) : Int64 := if x < y then if y < x then 1 else 2 else 3",
 "def f (x : Int64) : Int64 := if x <= 9223372036854775807 then 1 else 2",
 "def g (a b : UInt64) : UInt64 := a - b\ndef k : UInt64 := 7\ndef f (x y : UInt64) : UInt64 := if g (if x < y then x else y) 1 == 0 then k else g k x",
 "def f (x y : UInt64) : UInt64 := if x < y\n  then 1\n  else 2",
 "def f (x y : UInt64) : UInt64 := x &&& y ||| x ^^^ y",
 "def f (x y : UInt64) : UInt64 := x <<< 3 >>> 2 &&& y",
 "def b (o c : UInt64) : UInt64 := (o &&& 7) <<< 4 ||| (c >>> 1)\ndef f (x y : UInt64) : UInt64 := b x y ^^^ (x <<< 63)",
 "def f (x : UInt64) : UInt64 := if x &&& 1 == x - x then x >>> 1 else x <<< 1 ||| x",
 "def f (x y : UInt64) : UInt64 := x + y &&& x - y",
]
out = subprocess.run("PATH=$HOME/.elan/bin:$PATH lake env lean --stdin --run", shell=True, cwd=ROOT, capture_output=True, text=True,
  input="import Nano.V2Elab\ndef main : IO Unit := do\n" + "".join(
    f"  IO.println (repr (Nano.V2.nanoElab {json.dumps(s)}.toUTF8.toList)).pretty\n" for s in SRCS))
if out.returncode: print(out.stderr); raise SystemExit(2)
# `repr` of an Option prints `some (...)` on possibly several lines; split on top-level "some"/"none"
reprs = re.split(r"\n(?=some |none)", out.stdout.strip())
assert len(reprs) == len(SRCS), (len(reprs), out.stdout[:500])
L = ["import Nano.V2Elab",
     "/- GENERATED by Testing/nano/gen_agree_v2.py: nano v2 (if + comparisons) elaborator agreement with Lean's real",
     "elaborator.  Each source TEXT is also elaborated by Lean here (the defs of the namespace); `agree`: for ALL inputs, the",
     "v2 elaborator's program means what Lean's elaboration of the same text computes (Int64: on the two's complement bits). -/",
     "namespace NanoV2Agree", "open Nano.V2", "set_option linter.unusedVariables false", "set_option linter.unusedSimpArgs false", "",
     "theorem u_inj (a b : Int64) : a.toUInt64 = b.toUInt64 ↔ a = b :=",
     "  ⟨fun h => by simpa using congrArg UInt64.toInt64 h, fun h => h ▸ rfl⟩", ""]
for i, (s, r) in enumerate(zip(SRCS, reprs)):
    assert r.startswith("some "), (s, r)
    term = " ".join(r[len("some "):].split())
    names = re.findall(r"^def\s+(\w+)", s, re.M)
    ent = names[-1]
    k = sum(len(g.split(":")[0].split()) for g in re.findall(r"\(([^)]*)\)", re.findall(r"^def\s+\w+((?:\s*\([^)]*\))*)\s*:", s, re.M)[-1]))
    signed = re.search(r"\bInt64", s) is not None
    xs = " ".join(f"x{j}" for j in range(k))
    args = ", ".join((f"x{j}.toUInt64" if signed else f"x{j}") for j in range(k))
    res = f"({ent} {xs}).toUInt64" if signed else f"({ent} {xs})"
    ty = "Int64" if signed else "UInt64"
    binder = f"∀ {xs} : {ty}, " if k else ""
    intro = f"intro {xs}; " if k else ""
    L += [f"namespace P{i}", s, f"def src : String := {json.dumps(s)}",
          "theorem bytes_eq : src.toUTF8.toList = src.toList.map (fun c => c.toNat.toUInt8) := by decide +kernel",
          f"theorem elabEq : nanoElab (src.toList.map (fun c => c.toNat.toUInt8)) = some {term} := by decide +kernel",
          f"theorem agree : {binder}(nanoElab src.toUTF8.toList).bind (·.eval [{args}]) = some {res} := by",
          f"  {intro}rw [bytes_eq, elabEq]",
          f"  simp [Prog.eval, den, denA, Cmp.test, u_inj, apply_ite Int64.toUInt64, {', '.join(names)}]",
          "  all_goals repeat' (first | rfl | decide | (split <;> simp_all [u_inj]))",
          f"end P{i}", ""]
L.append("end NanoV2Agree")
open(os.path.join(ROOT, "Nano", "V2Agree.lean"), "w").write("\n".join(L) + "\n")
print(len(SRCS), "programs")
