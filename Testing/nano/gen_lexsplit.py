#!/usr/bin/env python3
"""Generates the step macros of the split lexer (Legacy/Nano/ElabBSplit.lean, branch nano-closeA) from the templates of
`Nano.B.lx` (Testing/nano/elabb_{step,end}.tmpl; see gen_elabb.py):
  V (`lv`):   the validator: passes 5 and 0 of `lx`, every emitting alternative `if m == 0 then REC else BYTES :: REC`
              resolved to `REC`; the end of pass 0 restarts in mode 1 = copy the source (output `ty :: source`).
  R (`vres`): the same run as an `Option UInt64` (`none` = rejected, `some ty` = accepted with type `ty`), Lean only.
  E (`le`):   the emitter: pass 1 of `lx` (alternatives resolved to `BYTES :: REC`, the mode-5 branch dropped), behind
              mode 7 = read the type byte written by `lv` (0: rejected).

usage: gen_lexsplit.py elabb_step.tmpl elabb_end.tmpl [V,R | E] (the variants to print; default all)"""
import re, sys
TN = open(sys.argv[1]).read(); TE = open(sys.argv[2]).read()
def args(s, i):  # s[i] == '(' ; split top-level commas
    depth, cur, out, j = 0, '', [], i
    while True:
        ch = s[j]
        if ch == '(':
            depth += 1
            if depth == 1: j += 1; continue
        elif ch == ')':
            depth -= 1
            if depth == 0: out.append(cur.strip()); return out, j + 1
        elif ch == ',' and depth == 1:
            out.append(cur.strip()); cur = ''; j += 1; continue
        cur += ch; j += 1
def group_end(s, i):  # end of the balanced group / REC call / term starting at i (i at '(' or 'R')
    if s.startswith('REC(', i): return args(s, i + 3)[1]
    assert s[i] == '(', s[i:i + 20]
    depth = 0
    for j in range(i, len(s)):
        if s[j] == '(': depth += 1
        elif s[j] == ')':
            depth -= 1
            if depth == 0: return j + 1
def resolve_m0(s, keep):
    """`if m == 0 then REC(..) else Y` (Y up to the enclosing paren) -> REC(..) (keep='rec') or Y (keep='emit')"""
    while True:
        k = s.find('if m == 0 then REC(')
        if k < 0: return s
        j = group_end(s, k + len('if m == 0 then '))
        rec = s[k + len('if m == 0 then '):j]
        m = re.compile(r'\s*else\s+').match(s, j); assert m, s[j:j + 40]
        y0 = m.end(); depth = 0; e = y0
        while True:
            ch = s[e]
            if ch == '(': depth += 1
            elif ch == ')':
                if depth == 0: break
                depth -= 1
            e += 1
        s = s[:k] + (rec if keep == 'rec' else s[y0:e].rstrip()) + s[e:]
def drop_m5(s):
    k = s.find('if m == 5 then'); assert k >= 0
    i = re.compile(r'\s*').match(s, k + len('if m == 5 then')).end()
    j = group_end(s, i)
    m = re.compile(r'\s*else\s+').match(s, j); assert m
    return s[:k] + s[m.end():]
def w(x): return x if re.fullmatch(r'[\w.]+', x) else '(' + x + ')' if not x.startswith('(') else x
def subst(s, fn, end, V):
    s = s.replace('@N', 'n'); out, i = '', 0
    while True:
        k = s.find('REC(', i)
        if k < 0: return out + s[i:]
        a, j = args(s, k + 3); assert len(a) == 7, a
        if end:
            ty = w(a[5]); pre = s[max(0, k - 30):k]
            if V == 'E': r = '[]'
            elif pre.endswith('if m == 5 then '): r = f'({fn} o o 0 0 0 0 0 0 0 0)'
            elif V == 'V': r = f'(if {ty} == 0 then [0] else ({ty}).toUInt8 :: {fn} o o 1 0 0 0 0 0 {ty} 0)'
            else: r = f'(if {ty} == 0 then none else some {ty})'
        else:
            r = f'({fn} (n :: t) o m ' + ' '.join(w(x) for x in a) + ')'
        out += s[i:k] + r; i = j
def rej(s, V): return s.replace('[0]', 'none') if V == 'R' else s
def mac(name, body):
    return f'set_option hygiene false in\nmacro "{name}" : term => `(\n{body.rstrip()})\n'
outs = []
SEL = sys.argv[3].split(',') if len(sys.argv) > 3 else ['V', 'R', 'E']
for V, fn in (('V', 'lv'), ('R', 'vres'), ('E', 'le')):
    if V not in SEL: continue
    n_, e_ = TN, TE
    if V == 'E': n_, e_ = drop_m5(resolve_m0(n_, 'emit')), drop_m5(resolve_m0(e_, 'emit'))
    else: n_, e_ = resolve_m0(n_, 'rec'), resolve_m0(e_, 'rec')
    if V == 'V': e_ = drop_m5(e_)   # `lv` tests `m == 5` before (a path must not test a condition twice)
    n_ = rej(subst(n_, fn, False, V), V); e_ = rej(subst(e_, fn, True, V), V)
    assert 'm == 0' not in n_ + e_ and (V != 'E' or 'm == 5' not in n_ + e_), V
    outs.append(mac(f'STEPN{V}', n_)); outs.append(mac(f'STEPE{V}', e_))
print('-- generated by Testing/nano/gen_lexsplit.py from Testing/nano/elabb_{step,end}.tmpl (do not edit by hand)')
print('\n'.join(outs))
