#!/usr/bin/env python3
"""Writes ArmBlockCheck.lean: #guard blockJ j = <oracle block> for every distinct J instruction of the given RV files.
UNPROVEN glue (test generator).  usage: gen_check.py prog_rv.bin ... > ArmBlockCheck.lean"""
import struct, sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
import rv2arm
def lean(j):
    a = ' '.join('(%d)' % v if v < 0 else str(v) for v in j[1:])
    return '.%s %s' % (j[0], a)
seen = {}
for f in sys.argv[1:]:  # (synth_rv.py's program is passed as one of them by check_lean.sh)
    d = open(f, 'rb').read()
    for w in struct.unpack('<%dI' % (len(d) // 4), d):
        j = rv2arm.decode(w)
        seen.setdefault(j, rv2arm.block(j, 0 if j[0] not in ('beq','bne','bltu','bgeu','jal') else 70000))
# forms B2 does not contain: sp and x0 operands, far/negative offsets
for j in [('alu', 1, 5, 2, 2), ('alu', 2, 6, 2, 7), ('alu', 8, 7, 5, 2), ('alu', 3, 5, 0, 6), ('slli', 5, 2, 40),
          ('srli', 6, 2, 63), ('bne', 2, 5, -3), ('beq', 5, 2, 7), ('bltu', 2, 2, 1), ('ld', 5, 2, -1000),
          ('ld', 5, 8, 12), ('sd', 0, 8, 2000), ('sd', 5, 2, -8), ('lbu', 5, 6, -1), ('sb', 0, 6, -2048),
          ('addi', 5, 2, -16), ('addi', 0, 5, 3), ('addi', 5, 0, 2047), ('jalr', 0, 14)]:
    seen.setdefault(j, rv2arm.block(j, 100))
items = sorted(seen.items(), key=str)
print('/- generated by gen_check.py: rv2arm.py blocks = ArmBlock.blockJ on %d distinct J instructions -/' % len(items))
print('import Testing.nano.v2self.arm.ArmBlock\nopen ArmBlock CallProbe')
for k in range(0, len(items), 300):
    print('def t%d : List (J × List Nat) := [' % (k // 300))
    print(',\n'.join('  (%s, [%s])' % (lean(j), ', '.join(map(str, ws))) for j, ws in items[k:k + 300]) + ']')
    print('#guard t%d.all fun (j, ws) => blockJ j == ws' % (k // 300))
