#!/usr/bin/env python3
"""Generate boot/B1.lean = BootPrelude (TRUSTED, Array buffers) + self_S.lean (List UInt8 -> Array UInt8) + `main` (stdin bytes -> C.m -> stdout bytes), then
compile it with the Lean toolchain to the native executable boot/B1 (the Lean compiler is trusted).  usage: build_B1.py [--list]  (--list: List prelude reference build B1L)."""
import re, subprocess, sys, os
here = "Testing/nano/v2self/boot"
LIST = "--list" in sys.argv
S = open("Testing/nano/v2self/self_S.lean").read()
S = S.replace("import Nano.Main.Prelude\n", "")
if not LIST: S = S.replace("List UInt8", "Array UInt8").replace("[]", "#[]")
pre = open("Nano/Main/Prelude.lean").read() if LIST else open(f"{here}/BootPrelude.lean").read()
if LIST: pre = re.sub(r"/-.*?-/", "", pre, count=1, flags=re.S)
main = '''
def readAll (s : IO.FS.Stream) : IO ByteArray := do
  let mut acc := ByteArray.empty
  repeat
    let chunk ← s.read 65536
    if chunk.isEmpty then break
    acc := acc ++ chunk
  return acc

def wordsToBytes (b : Buf) : Array UInt8 := Id.run do
  let mut o : Array UInt8 := #[]
  for v in b do
    for i in [0:8] do
      o := o.push ((v >>> (8 * i).toUInt64).toUInt8)
  return o

def main (args : List String) : IO UInt32 := do
  let inp ← readAll (← IO.getStdin)
  let x := INPCONV
  let stdout ← IO.getStdout
  match args with
  | ["lex"] => stdout.write (ByteArray.mk (wordsToBytes (C.s10 x)))
  | ["parse"] => stdout.write (ByteArray.mk (wordsToBytes (C.y16 (C.s10 x))))
  | ["own"] => stdout.write (ByteArray.mk (wordsToBytes (C.o41 (C.y16 (C.s10 x)))))
  | _ => let out := C.m x
         stdout.write (ByteArray.mk (OUTCONV))
  return 0
'''
main = main.replace("INPCONV", "inp.toList" if LIST else "inp.toList.toArray").replace("OUTCONV", "out.toArray" if LIST else "out")
open(f"{here}/{'B1L' if LIST else 'B1'}.lean", "w").write("-- GENERATED by build_B1.py. " + ("List-prelude REFERENCE build (B1L)." if LIST else "TRUSTED bootstrap B1 (Lean compiler trusted).") + "\n" + pre + "\n" + S + main)
