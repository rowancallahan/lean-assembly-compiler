#!/usr/bin/env python3
"""Generate Testing/nano/v2self/self_S.lean = the NEW compiler C as ONE file in the self-language: Base + Lex2 + Par1 + Gen (g41) + driver m = bytes of g41 (y16 (s10 input)).
Plain concatenation in def order (callees first); imports/namespace lines of the parts are dropped."""
import re, sys
sys.path.insert(0, "Testing/nano/v2self")
import desugar
parts = ["Base", "Lex2", "Par1", "Gen"]
out = ["/- GENERATED by build_self_S.py: the new compiler C in nano's self-language (S).  Do not edit. -/", "import Nano.V2Self.Prelude", "namespace C", ""]
for p in parts:
    t = open(f"Nano/V2Self/C/{p}.lean").read()
    t = re.sub(r"/-.*?-/", "", t, count=1, flags=re.S) if t.lstrip().startswith("/-") else t
    t = "\n".join(l for l in t.split("\n") if not l.startswith(("import", "namespace", "end C")))
    t = desugar.rewrite(t)   # && || ≤ ≠ conditions -> eager 0/1 flags (the restricted S has none of them)
    out.append(f"-- ===== {p} =====\n" + t.strip("\n") + "\n")
out.append("""-- ===== driver =====
def m1 : Nat → Buf → UInt64 → List UInt8 → List UInt8
  | 0, b, i, o => o
  | n + 1, b, i, o =>
    if bsize b < i then o
    else if bsize b == i then o
    else
      let v := bget b i;
      m1 n b (i + 1) (put o v)

def m (x : List UInt8) : List UInt8 := m1 16777216 (g41 (y16 (s10 x))) 0 []
""")
out.append("end C\n")
open("Testing/nano/v2self/self_S.lean", "w").write("\n".join(out))
