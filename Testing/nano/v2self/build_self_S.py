#!/usr/bin/env python3
"""Generate Testing/nano/v2self/self_S.lean = the NEW compiler C as ONE file in the self-language: Base + Lex2 + Par1 + Own (o41) + Gen (g41) + driver m = bytes of g41 (o41 (y16 (s10 input))).
Plain concatenation in def order (callees first); imports/namespace lines of the parts are dropped."""
import re, sys
sys.path.insert(0, "Testing/nano/v2self")
parts = ["Base", "Lex2", "Dsg", "Par1", "Own", "Gen"]
out = ["/- GENERATED by build_self_S.py: the new compiler C in nano's self-language (S).  Do not edit. -/", "import Nano.Main.Prelude", "namespace C", ""]
for p in parts:
    t = open("Nano/" + {"Base": "Main/Chain", "Lex2": "Lexer/Lex2", "Dsg": "Lexer/Dsg", "Par1": "Parser/Par1", "Own": "Ownership/Own", "Gen": "Codegen/Gen"}[p] + ".lean").read()
    t = re.sub(r"/-.*?-/", "", t, count=1, flags=re.S) if t.lstrip().startswith("/-") else t
    t = "\n".join(l for l in t.split("\n") if not l.startswith(("import", "namespace", "end C")))
    # Gen.lean itself threads the real input `c` (first `List UInt8` param) through g41/g42/g40: no patching here.
    body = re.sub(r"/-.*?-/", "", t, flags=re.S)
    body = "\n".join(l.split("--")[0] for l in body.split("\n"))
    assert not re.search(r"(?<!&)&&(?!&)|(?<!\|)\|\|(?!\|)|≤|≠", body), f"{p}: not in the restricted spelling (no && || ≤ ≠): the source files ARE the S text, verbatim"
    out.append(f"-- ===== {p} =====\n" + t.strip("\n") + "\n")
out.append("""-- ===== driver =====
def m (x : List UInt8) : List UInt8 := g41 x (o41 (y16 (s10 x)))
""")
out.append("end C\n")
open("Testing/nano/v2self/self_S.lean", "w").write("\n".join(out))
