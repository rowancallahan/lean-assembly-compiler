#!/usr/bin/env python3
"""Whole-program differential fuzzer for the nano compiler B2 (unproven glue, like examples/run_examples.sh).

usage: nanofuzz.py SEED N WORKDIR [MUT=0.5] [INPUTS=4] [SHRINK=1]
  N programs: generated by nanogen.py (valid-biased) and, with probability MUT, mutated (mutate()).
  Each program (raw text, comments included) is compiled by B2 under nanorun, run by nanorun on INPUTS random inputs,
  and checked against the reference semantics (semrun_batch.lean, the pipeline of semrun.lean in one Lean process).
  Also: every B2 rejection is checked with the reference (must be REJ) and with `lean` on the Prelude + program.
  Accept side (owner rule: every program nano accepts is accepted by Lean with the same result): every program B2
  accepts is elaborated by `lake env lean` (`import Nano.Main.Prelude`, batches of 100 programs in one file, one
  namespace each, a flagged program re-checked alone on its exact text) and its `#eval m INPUT` must equal B2's output on
  every input B2 ran to completion.  Otherwise a FAIL, classed NANO-ACCEPTS-LEAN-REJECTS or VALUE (as lean_check.py).
  JOBS (env, default 4) Lean processes in parallel.
  Outputs: WORKDIR/summary.txt and WORKDIR/alarms/*.lean (minimized repros; see shrink()).
Categories: ALARM = B2 accepts what the reference rejects, B2 output differs from OK output, B2 traps, or B2 accepts a
program Lean rejects.  GAP = B2 rejects what the reference accepts (completeness, not soundness)."""
import os, re, random, subprocess, sys, shutil, collections, concurrent.futures as cf

HERE = os.path.dirname(os.path.abspath(__file__))
V2 = os.path.abspath(os.path.join(HERE, '..'))
ROOT = os.path.abspath(os.path.join(V2, '../../..'))
B2 = os.path.join(V2, 'B2.bin')
PRELUDE = os.path.join(ROOT, 'Nano/Main/Prelude.lean')
SEMBATCH = os.path.join(HERE, 'semrun_batch.lean')
LEAN_ENV = dict(os.environ, PATH=os.path.expanduser('~/.elan/bin') + os.pathsep + os.environ.get('PATH', ''),
                ELAN_NO_OVERRIDE_NOTICE='1')

SEED, N, WORK = int(sys.argv[1]), int(sys.argv[2]), os.path.abspath(sys.argv[3])
MUT = float(sys.argv[4]) if len(sys.argv) > 4 else 0.5
NIN = int(sys.argv[5]) if len(sys.argv) > 5 else 4
SHRINK = (sys.argv[6] if len(sys.argv) > 6 else '1') == '1'
R = random.Random(SEED)

def mutate(t):
    """One random text-level mutation (may or may not stay accepted: the reference decides)."""
    ops = []
    def rep1(old, new):
        def f(t):
            return t.replace(old, new, 1) if old in t else None
        return f
    ops += [rep1(' < ', ' <= '), rep1(' == ', ' != '), rep1(' == ', ' <= '), rep1('+ ', '/ '), rep1('+ ', '% '),
            rep1(' then ', ' && 1 == 1 then '), rep1('|||', '||'), rep1('<<<', '<<'), rep1('>>>', '>>'),
            rep1("len' x", 'len x'), rep1('def m ', 'def k '), rep1('(x : List UInt8) ', ''),
            rep1('put', 'Put'), rep1(': UInt64 := ', ': Nat := '), rep1(' := ', ' = '), rep1('; ', ' '),
            rep1('| 0, x', '| 1, x'), rep1('x 0 []', 'x 0 [] ++ []'), rep1(' x ', ' y '),
            lambda t: '-- note\n' + t, lambda t: '/- note -/\n' + t,
            lambda t: t.replace('(put ', '(put (put ', 1).replace('[]', '[] ', 1) if '(put ' in t else None,
            lambda t: t.replace('| n + 1, x, i, o => ', '| n + 1, x, i, o => (put ', 1).replace('\ndef m', ' 7)\ndef m', 1)
            if '| n + 1, x, i, o => ' in t else None,
            lambda t: t.replace('match', 'Match') if 'match' in t else t + '\n-- end\n']
    for _ in range(R.randrange(1, 3)):
        f = R.choice(ops)
        new = f(t)
        if new is not None:
            t = new
    if R.random() < 0.3:   # delete or duplicate one character
        i = R.randrange(len(t))
        t = t[:i] + (t[i+1:] if R.random() < 0.5 else t[i] + t[i:])
    return t

def run(exe, args):
    p = subprocess.run([exe] + args, capture_output=True, text=True)
    m = re.search(r'a0 = (-?\d+)', p.stderr)
    return p.returncode, (int(m.group(1)) if m else None)

def b2_compile(name, text):
    src = os.path.join(WORK, name + '.lean'); bn = os.path.join(WORK, name + '.bin')
    with open(src, 'w') as f: f.write(text)
    rc, a0 = run(os.path.join(WORK, 'nanorun'), [B2, src, bn])
    code = open(bn, 'rb').read() if os.path.exists(bn) else b''
    if rc == 3 or a0 is None: return 'trap', None
    if a0 == -1: return 'oom', None
    return ('acc' if code else 'rej'), bn

def b2_run(name, bn, inputs, work=None):
    out = []
    for k, inp in enumerate(inputs):
        ip = os.path.join(WORK, f'{name}.in{k}'); op = os.path.join(WORK, f'{name}.b2out{k}')
        if os.path.exists(op): os.remove(op)
        args = [bn, ip, op] + ([str(work)] if work else [])
        rc, a0 = run(os.path.join(WORK, 'nanorun'), args)
        if rc == 3 or a0 is None: out.append(('trap', None)); continue
        st = {0: 'ok', 1: 'ok', -1: 'oom', -2: 'cap'}.get(a0, f'a0={a0}')
        out.append((st, open(op, 'rb').read() if st == 'ok' else None))
    return out

def ref_batch(names, inputs_of):
    """one Lean process for all (name, input) pairs; returns {(name,k): (status, bytes|None)}"""
    man = os.path.join(WORK, 'manifest.txt'); res = os.path.join(WORK, 'results.txt')
    keys = []
    with open(man, 'w') as m:
        for nm in names:
            for k, _ in enumerate(inputs_of[nm]):
                keys.append((nm, k))
                m.write(f"{WORK}/{nm}.lean {WORK}/{nm}.in{k} {WORK}/{nm}.ref{k}\n")
    if os.path.exists(res): os.remove(res)
    env = dict(LEAN_ENV, MANIFEST=man, RESULTS=res)
    p = subprocess.run(['lake', 'env', 'lean', SEMBATCH], cwd=ROOT, env=env, capture_output=True, text=True)
    assert p.returncode == 0, p.stdout[-2000:] + p.stderr[-2000:]
    lines = open(res).read().split('\n')
    assert len(lines) - 1 == len(keys), 'semrun batch: result count differs from manifest'
    out = {}
    for (nm, k), st in zip(keys, lines):
        rp = os.path.join(WORK, f'{nm}.ref{k}')
        out[(nm, k)] = (st, open(rp, 'rb').read() if st == 'OK' else None)
    return out

def lean_ok(name, text):
    t = os.path.join(WORK, name + '.chk.lean')
    with open(t, 'w') as f: f.write(open(PRELUDE).read() + '\n' + text)
    return subprocess.run(['lean', t], capture_output=True, env=LEAN_ENV).returncode == 0

# ---- accept side: Lean must accept every B2-accepted program, with B2's outputs (approach of lean_check.py)
LHDR = "import Nano.Main.Prelude\nset_option maxRecDepth 10000\nset_option maxErrors 100000\n\n"

def lake_lean(fn):
    p = subprocess.run(['lake', 'env', 'lean', '-DmaxErrors=1000000', fn], cwd=ROOT, env=LEAN_ENV,
                       capture_output=True, text=True, timeout=3600)
    return p.stdout + p.stderr

def err_lines(out):
    """(line, message) of every error Lean reports"""
    return [(int(m[1]), m[2]) for m in re.finditer(r'\.lean:(\d+):\d+: error: ?(.*)', out)]

def evals(out):
    got = {}
    for m in re.finditer(r'\((\d+),\s*(\d+),\s*\[([0-9,\s]*)\]\)', out):
        got[(int(m[1]), int(m[2]))] = bytes(int(x) for x in m[3].split(',') if x.strip())
    return got

def lit(b): return '[' + ', '.join(str(c) for c in b) + ']'

def expected(v):
    """{k: B2 output} for the inputs B2 ran to completion (a 1 GiB rerun counts)"""
    e = {}
    for k, (st, out) in enumerate(v['b2r']):
        if st == 'ok': e[k] = out
        elif st == 'oom' and v['b2big'] and v['b2big'][k][0] == 'ok': e[k] = v['b2big'][k][1]
    return e

def lean_value(nm, j, v, got):
    for k, o in sorted(expected(v).items()):
        if got.get((j, k)) != o:
            g = got.get((j, k))
            return ('VALUE', f'input {k}: lean {lit(g) if g is not None else "no result"}, b2 {lit(o)}')
    return None

def lean_alone(nm, j, v, tag):
    fn = os.path.join(WORK, f'lean_{tag}_{nm}.lean')
    ev = [f'#eval ({j}, {k}, m {lit(inp)})' for k, inp in enumerate(v['inputs'])]
    with open(fn, 'w') as f: f.write(LHDR + v['text'] + '\n' + '\n'.join(ev) + '\n')
    out = lake_lean(fn)
    errs = err_lines(out)
    if errs: return ('NANO-ACCEPTS-LEAN-REJECTS', f'line {errs[0][0]}: {errs[0][1][:200]} ({os.path.basename(fn)})')
    return lean_value(nm, j, v, evals(out))

def lean_batch(tag, items):
    """items: [(name, verdict)]; returns [(name, class, detail)]"""
    fn = os.path.join(WORK, f'lean_{tag}.lean')
    parts, rng, ln = [LHDR.rstrip('\n'), ''], [], LHDR.count('\n') + 1
    for j, (nm, v) in enumerate(items):
        body = f'namespace Nf{j}\n' + v['text'] + f'\nend Nf{j}'
        n = body.count('\n') + 1; rng.append((ln, ln + n)); ln += n; parts.append(body)
    erng = []
    for j, (nm, v) in enumerate(items):
        a = ln
        for k, inp in enumerate(v['inputs']):
            parts.append(f'#eval ({j}, {k}, Nf{j}.m {lit(inp)})'); ln += 1
        erng.append((a, ln))
    with open(fn, 'w') as f: f.write('\n'.join(parts) + '\n')
    out = lake_lean(fn)
    errl = [l for l, _ in err_lines(out)]
    got = evals(out)
    res = []
    for j, (nm, v) in enumerate(items):
        flagged = any(a <= l < b for l in errl for a, b in (rng[j], erng[j]))
        if any(l >= ln or l < rng[0][0] for l in errl): flagged = True   # an error outside every program: all alone
        r = lean_alone(nm, j, v, tag) if flagged else lean_value(nm, j, v, got)
        if r: res.append((nm,) + r)
    return res

def lean_accept_check(info, names):
    acc = [(nm, info[nm]) for nm in names if info[nm]['b2c'] == 'acc']
    chunks = [acc[j:j + 100] for j in range(0, len(acc), 100)]
    with cf.ThreadPoolExecutor(int(os.environ.get('JOBS', '4'))) as ex:
        outs = list(ex.map(lambda t: lean_batch(f'b{t[0]}', t[1]), enumerate(chunks)))
    nruns = sum(len(expected(v)) for _, v in acc)
    return len(acc), nruns, [r for o in outs for r in o]

def evaluate(items):
    """items: list of (name, text, inputs). Returns {name: verdict dict}."""
    info = {}
    for nm, text, inputs in items:
        for k, inp in enumerate(inputs):
            with open(os.path.join(WORK, f'{nm}.in{k}'), 'wb') as f: f.write(inp)
        cstat, bn = b2_compile(nm, text)
        b2r = b2_run(nm, bn, inputs) if cstat == 'acc' else None
        # out of work memory at the default 80 MiB: retry with 1 GiB, to tell a resource limit from a wrong answer
        b2big = b2_run(nm, bn, inputs, 1024) if b2r and any(st == 'oom' for st, _ in b2r) else None
        info[nm] = {'b2c': cstat, 'b2r': b2r, 'b2big': b2big, 'inputs': inputs, 'text': text}
    refs = ref_batch([nm for nm, _, _ in items], {nm: inp for nm, _, inp in items})
    with cf.ThreadPoolExecutor(4) as ex:
        rej = [it for it in items if info[it[0]]['b2c'] == 'rej']
        leans = dict(zip([nm for nm, _, _ in rej], ex.map(lambda it: lean_ok(it[0], it[1]), rej)))
    for nm in info:
        info[nm]['lean'] = leans.get(nm)
        info[nm]['ref'] = [refs[(nm, k)] for k in range(len(info[nm]['inputs']))]
    return info

def classify(v):
    """returns (category, is_alarm).  The Lean check is informational only: nano types numerals as UInt64, Lean as Nat."""
    if v['b2c'] == 'trap': return 'ALARM b2 compile trap', True
    if v['b2c'] == 'oom': return 'skip: b2 compile out of work memory', False
    rref0 = v['ref'][0][0]
    if v['b2c'] == 'rej':
        if rref0.startswith('REJ'):
            return 'reject agrees (ref REJ; lean ' + ('ok' if v['lean'] else 'fails') + ')', False
        return 'GAP: b2 rejects, ref ' + rref0, False
    if rref0.startswith('REJ'): return f'ALARM b2 accepts, ref {rref0}', True
    res = 'agree'
    for k, (b2st, b2out) in enumerate(v['b2r']):
        rst, rout = v['ref'][k]
        if rst == 'OK':
            if b2st == 'oom' and v['b2big'] and v['b2big'][k][0] == 'ok':
                if v['b2big'][k][1] != rout: return f'ALARM input {k}: output differs (1 GiB run)', True
                res = 'resource: b2 oom at 80 MiB, ok at 1 GiB with ref output'
                continue
            if b2st != 'ok': return f'ALARM input {k}: ref OK, b2 {b2st}', True
            if b2out != rout: return f'ALARM input {k}: output differs', True
        elif b2st == 'ok':   # ref STOP: B2 must not produce output
            return f'ALARM input {k}: ref {rst}, b2 ok', True
    return res, False

def same(res, cat):
    c, al = res
    key = lambda x: re.sub(r'input \d+', 'input', x)
    return al and key(c) == key(cat)

def shrink(name, text, inputs, cat):
    """line-level delta removal: keep removing one line at a time while the same ALARM category persists."""
    cur = text
    while True:
        lines = cur.split('\n')
        cands = [('%s_s%d' % (name, j), '\n'.join(lines[:j] + lines[j+1:]), inputs) for j in range(len(lines))]
        if not cands: return cur
        info = evaluate(cands)
        keep = [c for c in cands if same(classify(info[c[0]]), cat)]
        if not keep: return cur
        cur = keep[0][1]

def main():
    shutil.rmtree(WORK, ignore_errors=True); os.makedirs(WORK)
    gdir = os.path.join(WORK, 'gen')
    subprocess.run([sys.executable, os.path.join(HERE, 'nanogen.py'), str(SEED), str(N), gdir], check=True)
    cc = subprocess.run(['cc', '-O2', os.path.join(V2, 'run/nanorun.c'), '-o', os.path.join(WORK, 'nanorun')])
    assert cc.returncode == 0
    items = []
    for i in range(N):
        text = open(os.path.join(gdir, f'g{i}.src')).read()
        kind = 'g'
        if R.random() < MUT: text, kind = mutate(text), 'm'
        inputs = []
        for _ in range(NIN):
            n = R.choice([0, 1, 2, 3, 5, 8, 13, 40])
            inputs.append(bytes(R.randrange(256) for _ in range(n)))
        items.append((f'{kind}{i}', text, inputs))
    info = evaluate(items)
    cnt = collections.Counter(); alarms = []
    for nm, _, _ in items:
        cat, al = classify(info[nm])
        cnt[cat] += 1
        if al: alarms.append((nm, cat))
    os.makedirs(os.path.join(WORK, 'alarms'), exist_ok=True)
    minimized = {}
    for nm, cat in alarms:
        v = info[nm]
        path = os.path.join(WORK, 'alarms', nm + '.lean')
        with open(path, 'w') as f: f.write(v['text'])
        if SHRINK:
            small = shrink(nm, v['text'], v['inputs'], cat)
            print(f'{nm}: {cat} -> minimized to {len(small.splitlines())} lines')
            with open(os.path.join(WORK, 'alarms', nm + '.min.lean'), 'w') as f: f.write(small)
            minimized[nm] = small
    nacc, nruns, lfails = lean_accept_check(info, [nm for nm, _, _ in items])
    for nm, c, d in lfails:
        print(f'FAIL lean accept-side {nm}: {c}: {d}')
        with open(os.path.join(WORK, 'alarms', nm + '.leanfail.lean'), 'w') as f: f.write(info[nm]['text'])
    total = len(items)
    with open(os.path.join(WORK, 'summary.txt'), 'w') as f:
        f.write(f'seed={SEED} programs={total} mutated={sum(1 for n,_,_ in items if n[0]=="m")} inputs/program={NIN}\n')
        for c, k in sorted(cnt.items(), key=lambda t: -t[1]): f.write(f'{k:5d}  {c}\n')
        f.write(f'alarms={len(alarms)}\n')
        for nm, cat in alarms: f.write(f'  {nm}: {cat}\n')
        lc = collections.Counter(c for _, c, _ in lfails)
        f.write(f'lean accept-side: {nacc} b2-accepted programs, {nruns} runs compared; FAIL {len(lfails)} {dict(lc)}\n')
        for nm, c, d in lfails: f.write(f'  FAIL {nm}: {c}: {d}\n')
    print(open(os.path.join(WORK, 'summary.txt')).read())

if __name__ == '__main__':
    main()
