#!/usr/bin/env python3
"""usage: gen_layout.py MODE [FILE_IN [FILE_OUT]]  MODE = real | small.  Rewrites the LAYOUT block of Par0.lean (capacities in words; bases = prefix sums;
y15 = the heap initialisation with the total size as a NUMERAL: fuel arguments cannot be constants).  tokens are appended after the last region."""
import sys, re
mode = sys.argv[1]
f_in = sys.argv[2] if len(sys.argv) > 2 else "Nano/V2Self/C/Par0.lean"
f_out = sys.argv[3] if len(sys.argv) > 3 else f_in
caps = {"real": (12288, 4096, 16384 * 8, 32768, 4096), "small": (1536, 512, 1024 * 8, 12288, 1024)}[mode]   # task stack (3 words/task), operands, nodes*8, defs+shapes+flatten (Par1 needs >= 8192 + 3 * shapes), bindings (4 words each)
c = dict(zip(["d2", "d4", "d6", "d8", "d10"], caps))
base = 64; total = base + sum(caps)
blk = "-- LAYOUT BEGIN (generated by Testing/nano/v2self/gen_layout.py %s; regions are consecutive: bases are prefix sums of the capacities)\n" % mode
blk += "def d1 : UInt64 := 64\ndef d2 : UInt64 := %d\ndef d3 : UInt64 := d1 + d2\ndef d4 : UInt64 := %d\ndef d5 : UInt64 := d3 + d4\ndef d6 : UInt64 := %d\n" % caps[:3]
blk += "def d7 : UInt64 := d5 + d6\ndef d8 : UInt64 := %d\ndef d9 : UInt64 := d7 + d8\ndef d10 : UInt64 := %d\ndef d11 : UInt64 := d9 + d10\n" % caps[3:]
blk += "-- slot counts (direct index bounds; no k*x+c arithmetic): tasks, nodes, bindings, shapes\ndef d12 : UInt64 := %d\ndef d13 : UInt64 := %d\ndef d14 : UInt64 := %d\ndef d15 : UInt64 := %d\n" % (caps[0] // 3, caps[2] // 8, caps[4] // 4, (caps[3] - 8192) // 3)
blk += "def y15 (h : Buf) : Buf := y5 %d h\n-- LAYOUT END\n" % total
s = open(f_in).read()
a = s.index("-- LAYOUT BEGIN"); b = s.index("-- LAYOUT END\n") + len("-- LAYOUT END\n")
open(f_out, "w").write(s[:a] + blk + s[b:])
print(mode, "total words before tokens:", total)
