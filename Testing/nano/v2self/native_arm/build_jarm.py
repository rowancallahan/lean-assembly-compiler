#!/usr/bin/env python3
"""Write the nano texts of the J -> ARM translator (Nano/Codegen/JArm.lean), same rules as build_self_A.py:
  jarm_input.txt   the translator alone: m x = e45 x  (input: Gen's RISC-V code bytes; output: A64 code bytes)
  self_N.lean / self_N_input.txt   C with the translator as its back end: m x = e71 x (o41 (y16 (s10 x)))
PROTOTYPE, UNPROVEN."""
import re, os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../..")
d = os.path.dirname(os.path.abspath(__file__))
P = {"Base": "Main/Chain", "Lex2": "Lexer/Lex2", "Par1": "Parser/Par1", "Own": "Ownership/Own", "Gen": "Codegen/Gen",
     "JArm": "Codegen/JArm", "JArmTop": "Codegen/JArmTop"}
def stage(p):
    t = open(f"{R}/Nano/{P[p]}.lean").read()
    t = re.sub(r"/-.*?-/", "", t, flags=re.S)
    t = "\n".join(l.split("--")[0].rstrip() for l in t.split("\n") if not l.startswith(("import", "namespace", "end C")))
    assert not re.search(r"(?<!&)&&(?!&)|(?<!\|)\|\|(?!\|)|≤|≠", t), p
    return f"-- ===== {p} =====\n" + re.sub(r"\n{3,}", "\n\n", t).strip("\n") + "\n"
def write(name, stages, driver):
    out = [f"/- GENERATED by build_jarm.py.  Do not edit. -/", "import Nano.Main.Prelude", "namespace C", ""]
    out += [stage(p) for p in stages] + [f"-- ===== driver =====\n{driver}\n", "end C\n"]
    s = "\n".join(out)
    if name: open(f"{d}/{name}.lean", "w").write(s)
    a = s.split("\n", 4)[4].replace("end C\n", "")
    c = "\n".join(l for l in re.sub(r"/-.*?-/", "", a, flags=re.S).split("\n") if not l.startswith("--"))
    return re.sub(r"\n\n+", "\n\n", c)
open(f"{d}/jarm_input.txt", "w").write(write(None, ["JArm"], "def m (x : List UInt8) : List UInt8 := e45 x"))
open(f"{d}/self_N_input.txt", "w").write(write("self_N", ["Base", "Lex2", "Par1", "Own", "Gen", "JArm", "JArmTop"],
     "def m (x : List UInt8) : List UInt8 := e71 x (o41 (y16 (s10 x)))"))
