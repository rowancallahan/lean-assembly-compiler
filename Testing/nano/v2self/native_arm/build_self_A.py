#!/usr/bin/env python3
"""Write native_arm/self_A.lean = Base + Lex2 + Dsg + Par1 + Own + Gen + GenArm + driver m = a31 (o41 (y16 (t10 (s10 x)))): the compiler
with the NATIVE AArch64 back end (C/GenArm.lean), in nano's self-language.  Same rules as build_self_S.py.  Also writes
self_A_input.txt (the text B2 compiles: the file without comment lines).  PROTOTYPE, UNPROVEN."""
import re, os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../..")
out = ["/- GENERATED by build_self_A.py.  Do not edit. -/", "import Nano.Main.Prelude", "namespace C", ""]
for p in ["Base", "Lex2", "Dsg", "Par1", "Own", "Gen", "GenArm"]:
    t = open(f"{R}/Nano/<stages>/C/{p}.lean").read()
    t = re.sub(r"/-.*?-/", "", t, flags=re.S)
    t = "\n".join(l.split("--")[0].rstrip() for l in t.split("\n") if not l.startswith(("import", "namespace", "end C")))
    assert not re.search(r"(?<!&)&&(?!&)|(?<!\|)\|\|(?!\|)|≤|≠", t), p
    out.append(f"-- ===== {p} =====\n" + re.sub(r"\n{3,}", "\n\n", t).strip("\n") + "\n")
out.append("-- ===== driver =====\ndef m (x : List UInt8) : List UInt8 := a31 x (o41 (y16 (t10 (s10 x))))\n")
out.append("end C\n")
d = os.path.dirname(os.path.abspath(__file__))
s = "\n".join(out)
open(f"{d}/self_A.lean", "w").write(s)
a = s.split("\n", 4)[4].replace("end C\n", "")
c = "\n".join(l for l in re.sub(r"/-.*?-/", "", a, flags=re.S).split("\n") if not l.startswith("--"))
open(f"{d}/self_A_input.txt", "w").write(re.sub(r"\n\n+", "\n\n", c))
